const root = document.documentElement;
const systemDark = window.matchMedia("(prefers-color-scheme: dark)");
let currentLanguage = localStorage.getItem("portfolio-language") || "en";
let currentTheme = localStorage.getItem("portfolio-theme") || (systemDark.matches ? "dark" : "light");

function renderProjects() {
  const dictionary = translations[currentLanguage];
  const orderedProjects = [...projects].sort((a, b) => Number(Boolean(b.featured)) - Number(Boolean(a.featured)));
  document.querySelector("#projects-grid").innerHTML = orderedProjects.map((project, index) => `
    <article class="project-card${project.featured ? " featured" : ""}">
      <div class="project-meta"><span>PROJECT / ${String(index + 1).padStart(2, "0")}</span><span>${project.year}</span></div>
      <div class="project-visual" aria-hidden="true"><span class="project-glyph">${project.glyph}</span></div>
      ${project.featured ? `<span class="project-badge">${dictionary.flagship}</span>` : ""}
      <h3>${project.title[currentLanguage]}</h3>
      <p>${project.description[currentLanguage]}</p>
      <div class="tags">${project.tags.map(tag => `<span class="tag">${tag}</span>`).join("")}</div>
      ${project.href
        ? `<a class="project-link" href="${project.href}" target="_blank" rel="noreferrer">${dictionary.source}</a>`
        : `<span class="project-link">${dictionary.private}</span>`}
    </article>
  `).join("");
}

function renderAdditionalWork() {
  document.querySelector("#experience-list").innerHTML = additionalWork.map(item => `
    <article class="experience-item">
      <span class="experience-code">${item.code}</span>
      <h3>${item.title[currentLanguage]}</h3>
      <p>${item.description[currentLanguage]}</p>
      <div class="experience-tags">${item.tags.map(tag => `<span class="tag">${tag}</span>`).join("")}</div>
    </article>
  `).join("");
}

function setLanguage(language) {
  currentLanguage = translations[language] ? language : "en";
  localStorage.setItem("portfolio-language", currentLanguage);
  root.lang = currentLanguage;
  document.querySelectorAll("[data-i18n]").forEach(node => {
    const value = translations[currentLanguage][node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll(".language-button").forEach(button => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  renderProjects();
  renderAdditionalWork();
}

function setTheme(theme) {
  currentTheme = theme === "light" ? "light" : "dark";
  localStorage.setItem("portfolio-theme", currentTheme);
  root.dataset.theme = currentTheme;
  document.querySelector('meta[name="theme-color"]').content = currentTheme === "dark" ? "#090909" : "#f3f3ef";
  document.querySelector(".theme-button").setAttribute("aria-pressed", String(currentTheme === "light"));
}

document.querySelectorAll(".language-button").forEach(button => button.addEventListener("click", () => setLanguage(button.dataset.lang)));
document.querySelector(".theme-button").addEventListener("click", () => setTheme(currentTheme === "dark" ? "light" : "dark"));
document.querySelector("[data-scroll-top]").addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));
document.querySelector("#year").textContent = new Date().getFullYear();
setTheme(currentTheme);
setLanguage(currentLanguage);

document.querySelectorAll("[data-copy]").forEach(card => {
  function copyValue() {
    const text = card.dataset.copy;
    navigator.clipboard.writeText(text).then(() => {
      const toast = card.querySelector(".copy-toast");
      if (toast) {
        toast.classList.add("visible");
        setTimeout(() => toast.classList.remove("visible"), 1600);
      }
    });
  }
  card.addEventListener("click", copyValue);
  card.addEventListener("keydown", e => {
    if (e.key === "Enter" || e.key === " ") { e.preventDefault(); copyValue(); }
  });
});
